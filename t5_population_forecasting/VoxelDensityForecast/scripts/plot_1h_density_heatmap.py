from __future__ import annotations

"""Render a one-hour voxel-density prediction against its closed-cohort truth.

The prediction input follows ``scripts/predict.py``: ``expected_count`` is
stored by lead together with ``horizons_hours`` and ``origin_time_ns``.  The
truth is reconstructed from the matching closed-cohort shard so the figure
does not require a second, manually prepared truth file.
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
from typing import Any, Iterable

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from starlink_forecast.config import config_digest, grid_from_config, load_config, resolve_project_path
from starlink_forecast.voxel import aggregate_cic


HORIZON_HOURS = 1
OUTPUT_FILENAMES = (
    "one_hour_density_heatmap.png",
    "one_hour_density_heatmap.pdf",
    "one_hour_density_heatmap.json",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Render +1 h closed-cohort CIC truth, expected-count prediction, "
            "and absolute-error longitude-latitude heatmaps."
        )
    )
    parser.add_argument("--config", default=str(ROOT / "configs" / "default.yaml"))
    parser.add_argument(
        "--prediction",
        required=True,
        help="NPZ generated by scripts/predict.py or an equivalent result exporter.",
    )
    parser.add_argument(
        "--truth-shard",
        help="Closed-cohort NPZ containing the prediction origin; auto-discovered when omitted.",
    )
    parser.add_argument(
        "--shard-dir",
        help="Directory searched when --truth-shard is omitted; defaults to paths.shard_dir.",
    )
    parser.add_argument(
        "--view",
        choices=("column-sum", "altitude-layer"),
        default="column-sum",
        help="Sum all altitude layers or render one 50 km layer.",
    )
    parser.add_argument(
        "--altitude-index",
        type=int,
        help="Zero-based layer for --view altitude-layer; defaults to the layer with most truth mass.",
    )
    parser.add_argument(
        "--output-dir",
        default="reports/figures/one_hour_density_heatmap",
        help="Directory receiving PNG, PDF, and JSON provenance outputs.",
    )
    parser.add_argument(
        "--mass-tolerance",
        type=float,
        default=1.0e-5,
        help="Maximum relative mass error accepted for prediction and truth.",
    )
    parser.add_argument("--dry-run", action="store_true", help="Validate and report without writing files.")
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def resolve_input_path(value: str | Path) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (ROOT / path).resolve()


def require_file(path: Path, description: str) -> Path:
    if not path.is_file():
        raise FileNotFoundError(f"{description} does not exist: {path}")
    return path


def scalar_int(value: np.ndarray, name: str) -> int:
    array = np.asarray(value)
    if array.size != 1:
        raise ValueError(f"{name} must contain exactly one value")
    return int(array.reshape(-1)[0])


def scalar_string(value: np.ndarray, name: str) -> str:
    array = np.asarray(value)
    if array.size != 1:
        raise ValueError(f"{name} must contain exactly one value")
    return str(array.reshape(-1)[0])


def require_keys(archive: np.lib.npyio.NpzFile, keys: Iterable[str], description: str) -> None:
    missing = [key for key in keys if key not in archive.files]
    if missing:
        raise ValueError(f"{description} is missing required arrays: {missing}")


def validate_count_array(value: np.ndarray, name: str, ndim: int) -> np.ndarray:
    array = np.asarray(value, dtype=np.float64)
    if array.ndim != ndim:
        raise ValueError(f"{name} must have {ndim} dimensions, got shape {array.shape}")
    if min(array.shape) <= 0:
        raise ValueError(f"{name} cannot contain an empty dimension")
    if not np.isfinite(array).all():
        raise ValueError(f"{name} contains non-finite values")
    if np.any(array < -1.0e-7):
        raise ValueError(f"{name} contains negative count values")
    return np.maximum(array, 0.0)


def normalize_joint(voxel: np.ndarray, outside: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    voxel_values = np.asarray(voxel, dtype=np.float64)
    outside_values = np.asarray(outside, dtype=np.float64)
    total = float(voxel_values.sum() + outside_values.sum())
    if total <= 0.0:
        raise ValueError("joint voxel and outside mass must be positive")
    return voxel_values / total, outside_values / total


def joint_tv(
    voxel_probability: np.ndarray,
    outside_probability: np.ndarray,
    target_voxel: np.ndarray,
    target_outside: np.ndarray,
) -> float:
    target_voxel_probability, target_outside_probability = normalize_joint(
        target_voxel, target_outside
    )
    return 0.5 * float(
        np.abs(voxel_probability - target_voxel_probability).sum()
        + np.abs(outside_probability - target_outside_probability).sum()
    )


def regional_relative_mae(prediction: np.ndarray, target: np.ndarray) -> float:
    predicted = np.asarray(prediction, dtype=np.float64)
    observed = np.asarray(target, dtype=np.float64)
    if predicted.shape != observed.shape or predicted.ndim != 3:
        raise ValueError("regional MAE inputs must share one three-dimensional grid")
    factors = (2, 2, 2)
    if any(size % factor for size, factor in zip(predicted.shape, factors)):
        raise ValueError("grid dimensions must be divisible by the regional pooling factors")
    depth, latitude, longitude = predicted.shape
    pooled_prediction = predicted.reshape(
        depth // 2, 2, latitude // 2, 2, longitude // 2, 2
    ).sum(axis=(1, 3, 5))
    pooled_target = observed.reshape(
        depth // 2, 2, latitude // 2, 2, longitude // 2, 2
    ).sum(axis=(1, 3, 5))
    return float(np.abs(pooled_prediction - pooled_target).sum() / max(observed.sum(), 1.0))


def load_prediction(path: Path) -> dict[str, Any]:
    with np.load(path, allow_pickle=False) as archive:
        require_keys(
            archive,
            (
                "selected_model",
                "origin_time_ns",
                "horizons_hours",
                "satellite_ids",
                "expected_count",
                "outside_expected_count",
                "grid_shape",
                "height_min_km",
                "height_step_km",
                "lat_step_deg",
                "lon_step_deg",
            ),
            "prediction NPZ",
        )
        horizons = np.asarray(archive["horizons_hours"], dtype=np.int64).reshape(-1)
        lead_matches = np.flatnonzero(horizons == HORIZON_HOURS)
        if lead_matches.size != 1:
            raise ValueError(
                f"prediction must contain exactly one {HORIZON_HOURS} h lead; found {horizons.tolist()}"
            )
        expected_all = validate_count_array(archive["expected_count"], "expected_count", 4)
        outside_all = validate_count_array(
            archive["outside_expected_count"], "outside_expected_count", 2
        )
        if expected_all.shape[0] != horizons.size or outside_all.shape != (horizons.size, 2):
            raise ValueError("prediction lead dimensions do not match horizons_hours")
        lead_index = int(lead_matches[0])
        expected = expected_all[lead_index].copy()
        outside = outside_all[lead_index].copy()
        stored_grid_shape = tuple(int(value) for value in np.asarray(archive["grid_shape"]).reshape(-1))
        if stored_grid_shape != expected.shape:
            raise ValueError(
                f"grid_shape {stored_grid_shape} does not match expected_count {expected.shape}"
            )
        satellite_ids = tuple(str(value) for value in np.asarray(archive["satellite_ids"]).reshape(-1))
        if not satellite_ids or len(set(satellite_ids)) != len(satellite_ids):
            raise ValueError("prediction satellite_ids must be nonempty and unique")
        return {
            "schema_version": scalar_int(archive["schema_version"], "schema_version")
            if "schema_version" in archive.files
            else None,
            "selected_model": scalar_string(archive["selected_model"], "selected_model"),
            "origin_time_ns": scalar_int(archive["origin_time_ns"], "origin_time_ns"),
            "horizons_hours": horizons,
            "lead_index": lead_index,
            "satellite_ids": satellite_ids,
            "expected_count": expected,
            "outside_expected_count": outside,
            "grid_shape": stored_grid_shape,
            "height_min_km": float(np.asarray(archive["height_min_km"]).reshape(-1)[0]),
            "height_step_km": float(np.asarray(archive["height_step_km"]).reshape(-1)[0]),
            "lat_step_deg": float(np.asarray(archive["lat_step_deg"]).reshape(-1)[0]),
            "lon_step_deg": float(np.asarray(archive["lon_step_deg"]).reshape(-1)[0]),
        }


def matching_origin(path: Path, origin_time_ns: int) -> tuple[int, int] | None:
    with np.load(path, allow_pickle=False) as archive:
        require_keys(archive, ("time_ns", "origin_indices"), f"truth shard {path.name}")
        time_ns = np.asarray(archive["time_ns"], dtype=np.int64)
        origins = np.asarray(archive["origin_indices"], dtype=np.int64)
        if origins.ndim != 1 or np.any(origins < 0) or np.any(origins >= len(time_ns)):
            raise ValueError(f"truth shard has invalid origin_indices: {path}")
        matches = np.flatnonzero(time_ns[origins] == int(origin_time_ns))
        if matches.size > 1:
            raise ValueError(f"truth shard contains duplicate origin time {origin_time_ns}: {path}")
        if not matches.size:
            return None
        dataset_index = int(matches[0])
        return dataset_index, int(origins[dataset_index])


def find_truth_shard(
    *,
    explicit_shard: Path | None,
    shard_dir: Path,
    origin_time_ns: int,
) -> tuple[Path, int, int]:
    candidates = [require_file(explicit_shard, "truth shard")] if explicit_shard else sorted(shard_dir.glob("*.npz"))
    if not candidates:
        raise FileNotFoundError(f"no closed-cohort NPZ shards were found in {shard_dir}")
    matches: list[tuple[Path, int, int]] = []
    for path in candidates:
        match = matching_origin(path, origin_time_ns)
        if match is not None:
            matches.append((path.resolve(), match[0], match[1]))
    if not matches:
        raise ValueError(f"no truth shard contains prediction origin_time_ns={origin_time_ns}")
    if len(matches) > 1:
        raise ValueError(f"multiple truth shards contain prediction origin_time_ns={origin_time_ns}")
    return matches[0]


def load_truth(
    *,
    shard_path: Path,
    config: dict[str, Any],
    origin_time_ns: int,
    raw_origin_index: int,
) -> dict[str, Any]:
    with np.load(shard_path, allow_pickle=False) as archive:
        require_keys(
            archive,
            (
                "config_digest",
                "satellite_ids",
                "horizons_hours",
                "time_ns",
                "geodetic",
                "velocity_enu_km_s",
                "state_age_seconds",
                "valid",
            ),
            f"truth shard {shard_path.name}",
        )
        stored_digest = scalar_string(archive["config_digest"], "config_digest")
        if stored_digest != config_digest(config):
            raise ValueError("truth shard and runtime configuration digests do not match")
        horizons = np.asarray(archive["horizons_hours"], dtype=np.int64).reshape(-1)
        if np.count_nonzero(horizons == HORIZON_HOURS) != 1:
            raise ValueError(f"truth shard does not contain exactly one {HORIZON_HOURS} h lead")
        time_ns = np.asarray(archive["time_ns"], dtype=np.int64)
        valid = np.asarray(archive["valid"], dtype=bool)
        satellite_ids = np.asarray(archive["satellite_ids"]).astype(str)
        if valid.ndim != 2 or valid.shape[0] != time_ns.size or valid.shape[1] != satellite_ids.size:
            raise ValueError("truth shard time, validity, and satellite dimensions do not agree")
        if raw_origin_index < 0 or raw_origin_index >= time_ns.size:
            raise ValueError("truth raw origin index is outside the time axis")
        if int(time_ns[raw_origin_index]) != int(origin_time_ns):
            raise ValueError("truth raw origin index does not match prediction origin_time_ns")
        target_index = raw_origin_index + HORIZON_HOURS
        if target_index >= time_ns.size:
            raise ValueError("truth shard ends before the +1 h target")
        expected_target_time_ns = int(origin_time_ns) + 3_600_000_000_000
        if int(time_ns[target_index]) != expected_target_time_ns:
            raise ValueError("truth shard does not have an exact hourly sample at the +1 h target")
        members = valid[raw_origin_index]
        member_count = int(members.sum())
        if member_count <= 0:
            raise ValueError("truth origin has no known members")
        target_members = members & valid[target_index]
        if bool(config["forecast"].get("require_complete_targets", True)) and not bool(
            target_members[members].all()
        ):
            raise ValueError("truth target is incomplete for the origin-known cohort")
        geodetic = np.asarray(archive["geodetic"][target_index, target_members], dtype=np.float64)
        velocity = np.asarray(
            archive["velocity_enu_km_s"][target_index, target_members], dtype=np.float64
        )
        state_age = np.asarray(
            archive["state_age_seconds"][target_index, target_members], dtype=np.float64
        )
        origin_satellite_ids = tuple(str(value) for value in satellite_ids[members])
    grid = grid_from_config(config)
    aggregate = aggregate_cic(
        geodetic[:, 0],
        geodetic[:, 1],
        geodetic[:, 2],
        velocity,
        state_age,
        grid,
    )
    return {
        "target_counts": validate_count_array(aggregate.count_mass, "target_counts", 3),
        "target_outside": validate_count_array(aggregate.outside_count, "target_outside", 1),
        "future_total": float(member_count),
        "satellite_ids": origin_satellite_ids,
    }


def compare_population(prediction_ids: tuple[str, ...], truth_ids: tuple[str, ...]) -> None:
    predicted = set(prediction_ids)
    truth = set(truth_ids)
    if predicted == truth:
        return
    only_prediction = sorted(predicted - truth)[:5]
    only_truth = sorted(truth - predicted)[:5]
    raise ValueError(
        "prediction and truth do not use the same origin-known population; "
        f"prediction_only={only_prediction}, truth_only={only_truth}, "
        f"counts=({len(predicted)}, {len(truth)})"
    )


def validate_grid(prediction: dict[str, Any], config: dict[str, Any]) -> None:
    grid = grid_from_config(config)
    expected = {
        "grid_shape": tuple(int(value) for value in grid.shape),
        "height_min_km": float(grid.height_min_km),
        "height_step_km": float(grid.height_step_km),
        "lat_step_deg": float(grid.lat_step_deg),
        "lon_step_deg": float(grid.lon_step_deg),
    }
    if prediction["grid_shape"] != expected["grid_shape"]:
        raise ValueError(
            f"prediction grid {prediction['grid_shape']} does not match config grid {expected['grid_shape']}"
        )
    for name in ("height_min_km", "height_step_km", "lat_step_deg", "lon_step_deg"):
        if not np.isclose(float(prediction[name]), expected[name], rtol=0.0, atol=1.0e-6):
            raise ValueError(
                f"prediction {name}={prediction[name]} does not match config value {expected[name]}"
            )


def mass_statistics(
    *,
    predicted: np.ndarray,
    predicted_outside: np.ndarray,
    target: np.ndarray,
    target_outside: np.ndarray,
    expected_total: float,
    tolerance: float,
) -> dict[str, float]:
    if not np.isfinite(expected_total) or expected_total <= 0.0:
        raise ValueError("future_total must be finite and positive")
    predicted_total = float(predicted.sum() + predicted_outside.sum())
    target_total = float(target.sum() + target_outside.sum())
    predicted_error = abs(predicted_total - expected_total) / expected_total
    target_error = abs(target_total - expected_total) / expected_total
    if predicted_error > tolerance:
        raise ValueError(
            f"prediction relative mass error {predicted_error:.6g} exceeds tolerance {tolerance:.6g}"
        )
    if target_error > tolerance:
        raise ValueError(f"truth relative mass error {target_error:.6g} exceeds tolerance {tolerance:.6g}")
    predicted_probability, predicted_outside_probability = normalize_joint(predicted, predicted_outside)
    tv = joint_tv(predicted_probability, predicted_outside_probability, target, target_outside)
    regional_error = regional_relative_mae(predicted, target) + float(
        np.abs(predicted_outside - target_outside).sum() / max(target_total, 1.0)
    )
    return {
        "future_total": expected_total,
        "prediction_in_grid_mass": float(predicted.sum()),
        "prediction_outside_below_mass": float(predicted_outside[0]),
        "prediction_outside_above_mass": float(predicted_outside[1]),
        "prediction_total_mass": predicted_total,
        "prediction_relative_mass_error": predicted_error,
        "truth_in_grid_mass": float(target.sum()),
        "truth_outside_below_mass": float(target_outside[0]),
        "truth_outside_above_mass": float(target_outside[1]),
        "truth_total_mass": target_total,
        "truth_relative_mass_error": target_error,
        "joint_tv": float(tv),
        "density_mass_overlap_percent": float(100.0 * (1.0 - tv)),
        "regional_relative_mae": float(regional_error),
    }


def select_maps(
    target: np.ndarray,
    prediction: np.ndarray,
    *,
    view: str,
    requested_altitude_index: int | None,
    height_min_km: float,
    height_step_km: float,
) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    if target.shape != prediction.shape or target.ndim != 3:
        raise ValueError("truth and prediction must share [height, latitude, longitude] shape")
    if view == "column-sum":
        if requested_altitude_index is not None:
            raise ValueError("--altitude-index can only be used with --view altitude-layer")
        truth_map = target.sum(axis=0)
        prediction_map = prediction.sum(axis=0)
        metadata = {
            "view": view,
            "altitude_index": None,
            "altitude_range_km": [height_min_km, height_min_km + target.shape[0] * height_step_km],
            "unit": "CIC mass / expected satellites per latitude-longitude column",
            "colorbar_label": "Satellite count mass per 5 deg x 5 deg column",
            "error_colorbar_label": "Absolute count-mass error per 5 deg x 5 deg column",
        }
    else:
        layer_mass = target.sum(axis=(1, 2))
        altitude_index = int(np.argmax(layer_mass)) if requested_altitude_index is None else requested_altitude_index
        if altitude_index < 0 or altitude_index >= target.shape[0]:
            raise ValueError(
                f"--altitude-index {altitude_index} is outside the grid's {target.shape[0]} layers"
            )
        truth_map = target[altitude_index]
        prediction_map = prediction[altitude_index]
        lower = height_min_km + altitude_index * height_step_km
        metadata = {
            "view": view,
            "altitude_index": altitude_index,
            "altitude_selection": "explicit"
            if requested_altitude_index is not None
            else "largest true CIC mass",
            "altitude_range_km": [lower, lower + height_step_km],
            "unit": "CIC mass / expected satellites per voxel",
            "colorbar_label": "Satellite count mass per 50 km x 5 deg x 5 deg voxel",
            "error_colorbar_label": "Absolute count-mass error per voxel",
        }
    maps = {
        "truth": np.asarray(truth_map, dtype=np.float64),
        "prediction": np.asarray(prediction_map, dtype=np.float64),
    }
    maps["absolute_error"] = np.abs(maps["prediction"] - maps["truth"])
    return maps, metadata


def utc_string(time_ns: int) -> str:
    return np.datetime_as_string(np.datetime64(int(time_ns), "ns"), unit="s") + "Z"


def output_paths(output_dir: Path) -> dict[str, Path]:
    return {
        "png": output_dir / OUTPUT_FILENAMES[0],
        "pdf": output_dir / OUTPUT_FILENAMES[1],
        "json": output_dir / OUTPUT_FILENAMES[2],
    }


def prepare_output_dir(output_dir: Path, overwrite: bool) -> dict[str, Path]:
    paths = output_paths(output_dir)
    if output_dir.exists() and not output_dir.is_dir():
        raise FileExistsError(f"output path exists and is not a directory: {output_dir}")
    output_dir.mkdir(parents=True, exist_ok=True)
    existing = [path for path in paths.values() if path.exists()]
    if existing and not overwrite:
        raise FileExistsError(
            f"output files already exist; choose another --output-dir or pass --overwrite: {existing}"
        )
    if overwrite:
        for path in existing:
            path.unlink()
    return paths


def render_figure(
    *,
    maps: dict[str, np.ndarray],
    metadata: dict[str, Any],
    prediction: dict[str, Any],
    output_png: Path,
    output_pdf: Path,
) -> None:
    try:
        import matplotlib
    except ImportError as error:
        raise RuntimeError(
            "Rendering requires Matplotlib. Install the project dependencies with: "
            "python -m pip install -e ."
        ) from error

    matplotlib.use("Agg", force=True)
    import matplotlib.pyplot as plt
    from matplotlib.colors import PowerNorm

    shared_maximum = max(
        float(maps["truth"].max()), float(maps["prediction"].max()), 1.0e-12
    )
    error_maximum = max(float(maps["absolute_error"].max()), 1.0e-12)
    shared_norm = PowerNorm(gamma=0.5, vmin=0.0, vmax=shared_maximum)
    error_norm = PowerNorm(gamma=0.5, vmin=0.0, vmax=error_maximum)
    figure, axes = plt.subplots(1, 3, figsize=(17, 5.2), layout="constrained")
    panels = (
        ("truth", "Ground truth: +1 h CIC target", "viridis", shared_norm, "map mass"),
        (
            "prediction",
            f"Prediction: {prediction['selected_model']}",
            "viridis",
            shared_norm,
            "map mass",
        ),
        ("absolute_error", "Absolute error", "magma", error_norm, "sum absolute error"),
    )
    images = []
    for axis, (key, title, color_map, norm, statistic_label) in zip(axes, panels):
        rendered = axis.imshow(
            maps[key],
            origin="lower",
            extent=(-180.0, 180.0, -90.0, 90.0),
            aspect="auto",
            interpolation="nearest",
            cmap=color_map,
            norm=norm,
        )
        images.append(rendered)
        axis.set_title(f"{title}\n{statistic_label} = {maps[key].sum():.3f}")
        axis.set_xlabel("Longitude (deg)")
        axis.set_ylabel("Latitude (deg)")
        axis.set_xticks(np.arange(-180, 181, 60))
        axis.set_yticks(np.arange(-90, 91, 30))
    shared_colorbar = figure.colorbar(images[1], ax=axes[:2].tolist(), shrink=0.86, pad=0.02)
    shared_colorbar.set_label(metadata["colorbar_label"])
    error_colorbar = figure.colorbar(images[2], ax=axes[2], shrink=0.86, pad=0.02)
    error_colorbar.set_label(metadata["error_colorbar_label"])
    origin_utc = utc_string(prediction["origin_time_ns"])
    target_utc = utc_string(prediction["origin_time_ns"] + 3_600_000_000_000)
    if metadata["view"] == "altitude-layer":
        altitude = metadata["altitude_range_km"]
        view_label = f"altitude [{altitude[0]:g}, {altitude[1]:g}) km"
    else:
        altitude = metadata["altitude_range_km"]
        view_label = f"altitude-summed [{altitude[0]:g}, {altitude[1]:g}) km"
    figure.suptitle(
        f"One-hour closed-cohort voxel-density forecast\n"
        f"origin {origin_utc} | target {target_utc} | {view_label}",
        fontsize=14,
    )
    figure.savefig(output_png, dpi=240, bbox_inches="tight")
    figure.savefig(output_pdf, bbox_inches="tight")
    plt.close(figure)


def write_json(path: Path, value: dict[str, Any]) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    if args.mass_tolerance < 0.0 or not np.isfinite(args.mass_tolerance):
        raise SystemExit("--mass-tolerance must be finite and non-negative")
    if args.altitude_index is not None and args.altitude_index < 0:
        raise SystemExit("--altitude-index must be non-negative")

    config_path = require_file(resolve_input_path(args.config), "config")
    config = load_config(config_path)
    prediction_path = require_file(resolve_input_path(args.prediction), "prediction")
    prediction = load_prediction(prediction_path)
    validate_grid(prediction, config)

    shard_dir = (
        resolve_input_path(args.shard_dir)
        if args.shard_dir
        else resolve_project_path(config, config["paths"]["shard_dir"])
    )
    explicit_shard = resolve_input_path(args.truth_shard) if args.truth_shard else None
    shard_path, dataset_origin_index, raw_origin_index = find_truth_shard(
        explicit_shard=explicit_shard,
        shard_dir=shard_dir,
        origin_time_ns=prediction["origin_time_ns"],
    )
    truth = load_truth(
        shard_path=shard_path,
        config=config,
        origin_time_ns=prediction["origin_time_ns"],
        raw_origin_index=raw_origin_index,
    )
    if prediction["expected_count"].shape != truth["target_counts"].shape:
        raise ValueError(
            "prediction and truth grid shapes differ: "
            f"{prediction['expected_count'].shape} vs {truth['target_counts'].shape}"
        )
    compare_population(prediction["satellite_ids"], truth["satellite_ids"])
    statistics = mass_statistics(
        predicted=prediction["expected_count"],
        predicted_outside=prediction["outside_expected_count"],
        target=truth["target_counts"],
        target_outside=truth["target_outside"],
        expected_total=truth["future_total"],
        tolerance=args.mass_tolerance,
    )
    maps, view_metadata = select_maps(
        truth["target_counts"],
        prediction["expected_count"],
        view=args.view,
        requested_altitude_index=args.altitude_index,
        height_min_km=prediction["height_min_km"],
        height_step_km=prediction["height_step_km"],
    )
    output_dir = resolve_input_path(args.output_dir)
    paths = output_paths(output_dir)
    report = {
        "schema_version": 1,
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "validated_dry_run" if args.dry_run else "rendered",
        "inputs": {
            "config": str(config_path),
            "prediction": str(prediction_path),
            "truth_shard": str(shard_path),
        },
        "selection": {
            "horizon_hours": HORIZON_HOURS,
            "prediction_lead_index": prediction["lead_index"],
            "truth_dataset_origin_index": dataset_origin_index,
            "truth_raw_origin_index": raw_origin_index,
            "origin_time_ns": prediction["origin_time_ns"],
            "origin_time_utc": utc_string(prediction["origin_time_ns"]),
            "target_time_utc": utc_string(prediction["origin_time_ns"] + 3_600_000_000_000),
            "selected_model": prediction["selected_model"],
        },
        "population": {
            "semantics": "same origin-known closed-cohort members",
            "matched": True,
            "satellite_count": len(prediction["satellite_ids"]),
        },
        "grid": {
            "shape": list(prediction["grid_shape"]),
            "height_min_km": prediction["height_min_km"],
            "height_step_km": prediction["height_step_km"],
            "lat_step_deg": prediction["lat_step_deg"],
            "lon_step_deg": prediction["lon_step_deg"],
        },
        "view": view_metadata,
        "metrics": statistics,
        "outputs": {name: str(path) for name, path in paths.items()},
        "interpretation_boundary": (
            "The figure compares CIC density mass for one aligned closed-cohort origin. "
            "It is descriptive and is not per-satellite exact-grid accuracy or formal model acceptance."
        ),
    }
    if args.dry_run:
        print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
        return 0

    paths = prepare_output_dir(output_dir, args.overwrite)
    render_figure(
        maps=maps,
        metadata=view_metadata,
        prediction=prediction,
        output_png=paths["png"],
        output_pdf=paths["pdf"],
    )
    write_json(paths["json"], report)
    print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


